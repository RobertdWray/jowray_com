import { createHash } from "node:crypto";

// README.md is the one source of truth for the three detailed diagrams on /how-it-was-built. These helpers find
// its Mermaid blocks for scripts/make-readme-diagrams.ts (which renders them to public/diagrams/*.svg) and for
// __tests__/lib/readme-diagrams.test.ts (which fails when README.md changes and the SVGs were not re-rendered),
// and hold the safety check both of them run on every SVG.

export interface ReadmeMermaidBlock {
  /** From the `## ` heading above the block, e.g. "how-a-memory-travels"; names the SVG file. */
  slug: string;
  /** That heading's text without its emoji, e.g. "How a memory travels". */
  heading: string;
  /** The fragment GitHub gives that heading on the repository page, without "#", e.g. "-how-a-memory-travels". */
  githubAnchor: string;
  /** The block's lines between the fences, exactly as written, joined with "\n". */
  source: string;
}

/** A CommonMark code fence: up to three spaces, then three or more backticks or tildes, then the info string. */
const FENCE = /^ {0,3}(`{3,}|~{3,})(.*)$/;

/** Strips the leading emoji and spaces from a README heading ("🧭 How a memory travels" → "How a memory travels"). */
function headingText(line: string): string {
  return line
    .replace(/^##\s+/, "")
    .replace(/^[^\p{L}\p{N}]+/u, "")
    .trim();
}

function slugify(heading: string): string {
  return heading
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/**
 * GitHub's heading id (github-slugger): lower-case, drop everything but letters, marks, numbers, connector
 * punctuation, spaces and hyphens, then spaces become hyphens. Emoji go, but an emoji's variation selector
 * (U+FE0F, a mark) stays: "🏗️ Architecture" becomes "️-architecture".
 */
export function githubHeadingAnchor(line: string): string {
  return line
    .replace(/^##\s+/, "")
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{M}\p{N}\p{Pc} -]/gu, "")
    .replace(/ /g, "-");
}

/**
 * Every ```mermaid block in the markdown, in order, named after the `## ` heading it sits under. Every fenced
 * block is tracked, so a `## ` line inside a ```bash or ~~~ block is not taken for a heading.
 * Throws on an unclosed Mermaid fence, a block before any `## ` heading, or two blocks under one heading, because
 * each of those would leave a diagram without a stable file name.
 */
export function readmeMermaidBlocks(markdown: string): ReadmeMermaidBlock[] {
  const blocks: ReadmeMermaidBlock[] = [];
  let heading: { text: string; anchor: string } | null = null;
  let fence: { marker: string; mermaid: boolean; lines: string[] } | null = null;

  for (const line of markdown.split(/\r?\n/)) {
    const fenceLine = FENCE.exec(line);
    if (fence) {
      const closes =
        fenceLine !== null &&
        fenceLine[1][0] === fence.marker[0] &&
        fenceLine[1].length >= fence.marker.length &&
        fenceLine[2].trim() === "";
      if (!closes) {
        fence.lines.push(line);
        continue;
      }
      if (fence.mermaid) {
        if (!heading) {
          throw new Error("A Mermaid block in README.md has no `## ` heading above it.");
        }
        const slug = slugify(heading.text);
        if (blocks.some((block) => block.slug === slug)) {
          throw new Error(`README.md has two Mermaid blocks under "## ${heading.text}"; give each its own heading.`);
        }
        blocks.push({ slug, heading: heading.text, githubAnchor: heading.anchor, source: fence.lines.join("\n") });
      }
      fence = null;
      continue;
    }
    if (fenceLine) {
      fence = { marker: fenceLine[1], mermaid: fenceLine[2].trim().split(/\s+/)[0] === "mermaid", lines: [] };
    } else if (line.startsWith("## ")) {
      heading = { text: headingText(line), anchor: githubHeadingAnchor(line) };
    }
  }
  if (fence?.mermaid) {
    throw new Error("README.md has a ```mermaid block that is never closed.");
  }
  return blocks;
}

/** The fingerprint the manifest and each SVG's header record for a block; hex SHA-256 of the source text. */
export function mermaidSourceHash(source: string): string {
  return createHash("sha256").update(source, "utf8").digest("hex");
}

const HEADER = /^<!-- Generated by scripts\/make-readme-diagrams\.ts from the "[^"]*" diagram in README\.md \(source sha256 ([0-9a-f]{64})\); do not edit by hand\. -->\n/;

/** The first line of every generated SVG: where it came from, and the SHA-256 of the README block it shows. */
export function svgHeader(heading: string, sourceSha256: string): string {
  return `<!-- Generated by scripts/make-readme-diagrams.ts from the "${heading}" diagram in README.md (source sha256 ${sourceSha256}); do not edit by hand. -->\n`;
}

/** The README block hash a generated SVG's header records, or null when the header is missing or malformed. */
export function svgSourceHash(svg: string): string | null {
  return HEADER.exec(svg)?.[1] ?? null;
}

// ---------------------------------------------------------------------------------------------------------------
// SVG safety check. The SVGs are served from this origin (public/diagrams/, opened by the "full size" links), so
// besides the Content-Security-Policy in next.config.ts, every file must hold only what the generator emits.
// This is an allowlist over a strict tokenizer: anything it cannot read, any element or attribute the generator
// does not produce, a repeated attribute, a namespace other than SVG's on the root (or any namespace declaration
// below it), and any reference other than a same-document `#id` (or, in CSS, the embedded WOFF2 fonts) is a
// problem. Entities are decoded before any value is checked; CSS escapes, CSS comments and XML comments inside
// <svg> are refused outright, so nothing can be hidden from a check that reads one piece at a time; DOCTYPEs,
// CDATA and processing instructions are unreadable by design. Widen an allowlist only after looking at what
// Mermaid emits.
// ---------------------------------------------------------------------------------------------------------------

const SVG_NAMESPACE = "http://www.w3.org/2000/svg";

/** Every element mermaid 12.2.0 emits for README.md's three diagrams with the generator's settings. */
const ALLOWED_ELEMENTS = new Set([
  "circle",
  "defs",
  "feDropShadow",
  "filter",
  "g",
  "line",
  "linearGradient",
  "marker",
  "path",
  "polygon",
  "rect",
  "stop",
  "style",
  "svg",
  "symbol",
  "text",
  "tspan",
]);

/** Every attribute it emits, plus `href`/`xlink:href`, which are held to same-document `#id` values. */
const ALLOWED_ATTRIBUTES = new Set([
  "alignment-baseline",
  "aria-roledescription",
  "class",
  "clip-rule",
  "cx",
  "cy",
  "d",
  "dominant-baseline",
  "dx",
  "dy",
  "fill",
  "fill-rule",
  "filter",
  "flood-color",
  "flood-opacity",
  "font-family",
  "font-size",
  "font-style",
  "font-weight",
  "gradientUnits",
  "height",
  "href",
  "id",
  "marker-end",
  "marker-start",
  "markerHeight",
  "markerUnits",
  "markerWidth",
  "name",
  "offset",
  "orient",
  "points",
  "r",
  "refX",
  "refY",
  "role",
  "rx",
  "ry",
  "stdDeviation",
  "stop-color",
  "stop-opacity",
  "stroke",
  "stroke-dasharray",
  "stroke-width",
  "style",
  "text-anchor",
  "transform",
  "viewBox",
  "width",
  "x",
  "x1",
  "x2",
  "xlink:href",
  "xmlns",
  "y",
  "y1",
  "y2",
]);
const DATA_ATTRIBUTE = /^data-[a-z][a-z0-9-]*$/;
const ALLOWED_AT_RULES = new Set(["font-face", "keyframes"]);

const TAG = /<(\/?)([A-Za-z_][\w:.-]*)((?:\s+[^\s=<>"'/]+\s*=\s*"[^"<]*")*)\s*(\/?)>/y;
const ATTRIBUTE = /\s+([^\s=<>"'/]+)\s*=\s*"([^"<]*)"/g;
const COMMENT = /<!--[\s\S]*?-->/y;
const ENTITY = /&(?:#([0-9]+)|#x([0-9a-fA-F]+)|(amp|lt|gt|quot|apos));/g;
const NAMED: Record<string, string> = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'" };

/** Decodes XML character references; any `&` that does not start one of them is reported. */
function decodeEntities(text: string, where: string, problems: string[]): string {
  if (/&(?!(?:#[0-9]+|#x[0-9a-fA-F]+|amp|lt|gt|quot|apos);)/.test(text)) {
    problems.push(`${where}: an "&" that is not one of XML's character references`);
  }
  return text.replace(ENTITY, (_, decimal: string | undefined, hex: string | undefined, name: string | undefined) => {
    if (name) {
      return NAMED[name];
    }
    const codePoint = decimal ? Number.parseInt(decimal, 10) : Number.parseInt(hex ?? "", 16);
    return codePoint <= 0x10ffff ? String.fromCodePoint(codePoint) : "�";
  });
}

/** A reference that stays in this document: markers, gradients and filters by id. */
function isFragment(value: string): boolean {
  return value.trim().startsWith("#");
}

/** The only `data:` URL the generator writes: an Atkinson Hyperlegible weight inside `@font-face`. */
const EMBEDDED_FONT = /^data:font\/woff2;base64,[A-Za-z0-9+/]+={0,2}$/;

/** Checks CSS from a <style> element or an attribute value (already entity-decoded). */
function cssProblems(code: string, where: string, allowAtRules: boolean, problems: string[]): void {
  if (code.includes("\\")) {
    problems.push(`${where}: a CSS escape (the generator never writes one, and they can disguise @import or url())`);
  }
  // Not stripped and then checked: a "/*" inside a CSS string would make the strip swallow real rules.
  if (code.includes("/*")) {
    problems.push(`${where}: a CSS comment (the generator never writes one, and one can hide url() or @import)`);
  }
  for (const [, rule] of code.matchAll(/@([A-Za-z-]+)/g)) {
    if (!allowAtRules || !ALLOWED_AT_RULES.has(rule.toLowerCase())) {
      problems.push(`${where}: CSS at-rule @${rule}`);
    }
  }
  for (const match of code.matchAll(/url\(/gi)) {
    const reference = /\s*(?:"([^"]*)"|'([^']*)'|([^)\s]*))/y;
    reference.lastIndex = (match.index ?? 0) + match[0].length;
    const found = reference.exec(code);
    const value = found ? (found[1] ?? found[2] ?? found[3] ?? "") : "";
    if (!isFragment(value) && !EMBEDDED_FONT.test(value.trim())) {
      problems.push(`${where}: url(${value.slice(0, 60)}) is not a #id or an embedded WOFF2 font`);
    }
  }
  if (/image-set\(|(?<![\w-])src\(/i.test(code)) {
    problems.push(`${where}: a CSS image-set() or src() reference`);
  }
  if (/expression\(|-moz-binding|behavior\s*:/i.test(code)) {
    problems.push(`${where}: legacy scriptable CSS`);
  }
}

function checkElement(name: string, attributes: string, isRoot: boolean, problems: string[]): void {
  const where = `<${name}>`;
  if (/^script$/i.test(name)) {
    problems.push(`${where}: script`);
  }
  if (/^foreignObject$/i.test(name)) {
    problems.push(`${where}: foreignObject can carry HTML`);
  }
  if (!ALLOWED_ELEMENTS.has(name)) {
    problems.push(`${where}: not an element the generator emits`);
  }
  if (isRoot && name !== "svg") {
    problems.push(`${where}: the root element is not <svg>`);
  }
  const seen = new Set<string>();
  for (const [, attribute, rawValue] of attributes.matchAll(ATTRIBUTE)) {
    const at = `${where} ${attribute}`;
    // XML forbids it, and a parser that kept the other copy would see a value this check never read.
    if (seen.has(attribute)) {
      problems.push(`${at}: a repeated attribute`);
    }
    seen.add(attribute);
    const value = decodeEntities(rawValue, at, problems);
    if (/^on/i.test(attribute)) {
      problems.push(`${at}: event-handler attribute`);
    }
    if (!ALLOWED_ATTRIBUTES.has(attribute) && !DATA_ATTRIBUTE.test(attribute)) {
      problems.push(`${at}: not an attribute the generator emits`);
    }
    if (/^(set|animate\w*)$/i.test(name) && attribute === "attributeName" && /^(on|href$|xlink:href$)/i.test(value)) {
      problems.push(`${at}: animates ${value}`);
    }
    if ((attribute === "href" || attribute === "xlink:href") && !isFragment(value)) {
      problems.push(`${at}: ${value.slice(0, 60)} is not a same-document #id`);
    }
    // Browsers ignore whitespace and control characters inside a URL scheme ("java\tscript:").
    const compact = Array.from(value)
      .filter((char) => (char.codePointAt(0) ?? 0) > 0x20)
      .join("");
    if (/javascript:/i.test(compact)) {
      problems.push(`${at}: javascript: URL`);
    }
    // A default namespace below the root would put allowed names (`style`, `svg`) in another vocabulary.
    if (attribute === "xmlns") {
      if (!isRoot) {
        problems.push(`${at}: a namespace declaration below the root (the generator writes xmlns only on <svg>)`);
      } else if (value !== SVG_NAMESPACE) {
        problems.push(`${at}: ${value.slice(0, 60)} is not the SVG namespace`);
      }
    }
    cssProblems(value, at, false, problems);
  }
  if (isRoot && !seen.has("xmlns")) {
    problems.push(`${where}: the root does not declare the SVG namespace`);
  }
}

/**
 * Everything in `svg` that is not on the generator's allowlist, as readable problems; an empty list means safe.
 * scripts/make-readme-diagrams.ts refuses to write a file with problems, and the tests run it on every committed
 * SVG and on known attack payloads.
 */
export function findUnsafeSvg(svg: string): string[] {
  const problems: string[] = [];
  const open: string[] = [];
  let roots = 0;
  let index = 0;
  while (index < svg.length) {
    if (svg.startsWith("<!--", index)) {
      // Text nodes are checked one at a time, so `u<!-- -->rl(` inside <style> would read as two harmless pieces.
      if (open.length > 0) {
        problems.push(`offset ${index}: a comment inside <svg> (the generator writes only its header comment, above it)`);
      }
      COMMENT.lastIndex = index;
      if (!COMMENT.exec(svg)) {
        problems.push(`offset ${index}: an unclosed comment`);
        break;
      }
      index = COMMENT.lastIndex;
      continue;
    }
    if (svg[index] === "<") {
      TAG.lastIndex = index;
      const tag = TAG.exec(svg);
      if (!tag) {
        problems.push(`offset ${index}: markup the check cannot read: ${JSON.stringify(svg.slice(index, index + 40))}`);
        break;
      }
      index = TAG.lastIndex;
      const [, closing, name, attributes, selfClosing] = tag;
      if (closing) {
        if (attributes || selfClosing || open.pop() !== name) {
          problems.push(`offset ${index}: a mismatched </${name}>`);
          break;
        }
        continue;
      }
      if (open.length === 0) {
        roots += 1;
      }
      checkElement(name, attributes, open.length === 0, problems);
      if (!selfClosing) {
        open.push(name);
      }
      continue;
    }
    const next = svg.indexOf("<", index);
    const end = next === -1 ? svg.length : next;
    const text = decodeEntities(svg.slice(index, end), `text at offset ${index}`, problems);
    if (open.length === 0 && text.trim() !== "") {
      problems.push(`offset ${index}: text outside the <svg> element`);
    }
    if (open.at(-1) === "style") {
      cssProblems(text, "<style>", true, problems);
    }
    index = end;
  }
  if (open.length > 0) {
    problems.push(`unclosed elements: ${open.join(" > ")}`);
  }
  if (roots !== 1) {
    problems.push(`${roots} root elements; expected one <svg>`);
  }
  return problems;
}
